"""Accuracy-loop N4 — does the calibration ritual work on real plucks?

`calibrate_from_ritual` (18 notes, three frets x six strings, fitting ``B0``
*and* the fret exponent) shipped with Q6 but has never been run on audio. The
state file recorded the blocker as:

    GuitarSet contains only 1-3 usable isolated open notes per player, so it
    cannot contain the ritual. Needs public capo/calibration audio or an
    explicit exception to the private-recordings ban.

**That blocker was measured against the mono microphone.** The ritual does not
need *open* strings or *temporally isolated* notes — it needs notes whose
(string, fret) is certain and whose ``B`` is measurable. GuitarSet ships
`audio_hex-pickup_debleeded`: one channel per string, with JAMS supplying the
label. An entry probe over four clips found **40 distinct (string, fret) cells
with >= 3 frets on all six strings**, against the 18 the ritual wants. The
channel/string mapping was verified rather than assumed (best-r2 fit per note
across all six channels is diagonal; the off-diagonal mass sits on *adjacent*
channels, the signature of residual pickup bleed rather than a permutation).

So the ritual is testable here, on public data, with no new download.

**This substrate is pessimistic, and deliberately so.** A real ritual is 18
deliberate plucks with nothing else sounding; these are performance excerpts
where neighbouring strings ring through an imperfect debleed. Whatever the
ritual achieves here is a lower bound on what a guided take would achieve.

Protocol. Per development player (00-04 — player 05 stays sealed):

* the first `RITUAL_CLIPS_PER_PLAYER` clips in sorted order are the
  *calibration take* and are **excluded from scoring**, so the ritual never
  sees the notes it is judged on. This mirrors real use, where the take is
  separate from the performance.
* a note enters the ritual only if its fit clears ``min_r2`` **and** the
  labelled channel is the best-fitting of the six — the bleed guard, standing
  in for "nothing else was sounding".
* at most `MAX_FRETS_PER_STRING` frets per string, best r2 per cell.
* the remaining clips are scored from the banked N5 measurements, so the
  scoring half is the same replay that was proved equal to
  `attach_inharmonicity_evidence`.

Arms, all scored on the same held-out clips against the same baseline:

* `shipped` — the registered specification-derived table. The control; it
  should reproduce the known full-dev effect on this subset.
* `ritual` — the per-player calibrated table, fitted ``log B0`` *and* fitted
  fret exponent.
* `ritual-level` — the shipped table shifted by the ritual's median level
  offset, exponent left at 1.0. Isolates how much of any gain is just the
  scalar that N5 showed the specification table is missing.
* `global-level` — **added after the first run, and therefore exploratory,
  not pre-declared.** The shipped table shifted by one constant shared by all
  players: the median of the five per-player ritual offsets. The first run
  showed `ritual-level` beating the full `ritual` fit, which raises the
  question this arm answers — does *per-player* calibration buy anything over
  a single corrected constant, or is the whole benefit a fixed level error in
  the specification table? Treat its comparison as a hypothesis generated by
  this data, to be confirmed elsewhere before it drives a default. (It carries
  no test leakage: each per-player offset comes from that player's own
  held-out ritual take, never from a scored clip.)

PRE-DECLARED READING (fixed before the run):

* **Validated** — the fitted fret exponent lands within 0.15 of the
  theoretical 1.0 on a majority of players, **and** `ritual` beats `shipped`
  with lo-95 > 0. The ritual works on real plucks and pays for itself.
* **Partial** — the exponent recovers but the Tab F1 delta over `shipped` has
  a CI spanning zero. The calibration math is sound; the payoff is below noise
  on this substrate, so calibration is a correctness feature and not an
  accuracy feature until measured on a real take.
* **Refuted** — the exponent is far from 1.0, or `ritual` is significantly
  *worse* than `shipped` (hi-95 < 0). The ritual design or the fret law needs
  revisiting before any calibration ships.

Two standing predictions are also on the line, both made before this run:

* Q6 measured the specification table low by **0.566 log** against its
  LOPO-fitted table. N5 then found the uniform-offset response still rising at
  +0.60 without turning over. If both are right, the ritual's recovered table
  should sit **above** the shipped one by roughly +0.4 to +0.7. A recovered
  offset near zero or negative would refute that reading.
* N5 put the headroom from a corrected level at up to **+0.016** Tab F1.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import time
from pathlib import Path
from typing import Any

import numpy as np
import soundfile as sf

from scripts.eval.n2_muscriptor_merge import (
    DEV_PLAYERS,
    _event_from_json,
    _score,
    build_oof_priors,
)
from scripts.eval.n5_table_mismatch import (
    BOOTSTRAP_N,
    BOOTSTRAP_SEED,
    MIN_R2,
    SIGMA,
    WEIGHT,
    apply_banked,
    offset_model,
)
from tabvision.eval.bootstrap import bootstrap_ci
from tabvision.eval.guitarset_audio import parse_guitarset_jams
from tabvision.fusion.inharmonicity import (
    MAX_WINDOW_S,
    MIN_WINDOW_S,
    SKIP_ATTACK_S,
    StiffnessObservation,
    StringStiffnessModel,
    calibrate_from_ritual,
    estimate_inharmonicity,
)
from tabvision.fusion.string_physics import reference_stiffness_model
from tabvision.types import GuitarConfig, SessionConfig

RITUAL_CLIPS_PER_PLAYER = 4
MAX_FRETS_PER_STRING = 3
N_STRINGS = 6


def _note_window(onset_s: float, duration_s: float, sr: int) -> tuple[int, int]:
    start = int((onset_s + SKIP_ATTACK_S) * sr)
    stop = start + int(min(MAX_WINDOW_S, duration_s - SKIP_ATTACK_S) * sr)
    return start, stop


def admit_note(
    audio: np.ndarray,
    sr: int,
    start: int,
    stop: int,
    f0_hz: float,
    string_idx: int,
    *,
    min_r2: float,
) -> tuple[float, float] | None:
    """Measure one note on its labelled hex channel, or decline.

    The bleed guard: the labelled channel must also be the *best-fitting* of
    the six. Debleeding is imperfect, and a note that rings through from a
    neighbour will still fit at this ``f0`` — without the guard it would
    supply the "measurement" for a string that was never plucked.

    Returns ``(log_b, r2)`` when admitted.
    """
    best_channel, best_r2 = -1, -1.0
    labelled = None
    for channel in range(N_STRINGS):
        fit = estimate_inharmonicity(audio[start:stop, channel], sr, f0_hz)
        if fit is None:
            continue
        if channel == string_idx:
            labelled = fit
        if fit.r2 > best_r2:
            best_channel, best_r2 = channel, fit.r2
    if labelled is None or labelled.r2 < min_r2:
        return None
    if best_channel != string_idx:
        return None
    return float(np.log(labelled.b)), labelled.r2


def measure_ritual_cells(
    track_ids: list[str], data_home: Path, cfg: GuitarConfig, *, min_r2: float
) -> tuple[dict[tuple[int, int], float], dict[str, Any]]:
    """Best measured ``log B`` per (string, fret), from hex audio."""
    cells: dict[tuple[int, int], tuple[float, float]] = {}
    tally = {"notes": 0, "windowed": 0, "admitted": 0}
    for track_id in track_ids:
        hex_path = data_home / "audio_hex-pickup_debleeded" / f"{track_id}_hex_cln.wav"
        if not hex_path.is_file():
            continue
        audio, sr = sf.read(str(hex_path), always_2d=True)
        sr = int(sr)
        gold = parse_guitarset_jams(data_home / "annotation" / f"{track_id}.jams", cfg)
        for note in gold:
            tally["notes"] += 1
            if note.duration_s < MIN_WINDOW_S + SKIP_ATTACK_S:
                continue
            start, stop = _note_window(note.onset_s, note.duration_s, sr)
            if start < 0 or stop > audio.shape[0]:
                continue
            tally["windowed"] += 1
            f0 = 440.0 * 2 ** ((note.pitch_midi - 69) / 12.0)
            admitted = admit_note(audio, sr, start, stop, f0, note.string_idx, min_r2=min_r2)
            if admitted is None:
                continue
            tally["admitted"] += 1
            log_b, r2 = admitted
            key = (note.string_idx, note.fret)
            previous = cells.get(key)
            if previous is None or r2 > previous[1]:
                cells[key] = (log_b, r2)
    return {key: value[0] for key, value in cells.items()}, dict(tally) | {
        "cells": len(cells),
        "_r2": {key: value[1] for key, value in cells.items()},
    }


def select_ritual(
    cells: dict[tuple[int, int], float],
    r2_by_cell: dict[tuple[int, int], float],
    *,
    max_frets: int = MAX_FRETS_PER_STRING,
) -> list[StiffnessObservation]:
    """Pick up to ``max_frets`` frets per string — the take the app would ask for.

    Frets are spread rather than best-r2-ranked: the exponent is a slope, and
    three frets clustered at the nut measure it far worse than three spread up
    the neck.
    """
    observations: list[StiffnessObservation] = []
    for string in range(N_STRINGS):
        frets = sorted(fret for (s, fret) in cells if s == string)
        if not frets:
            continue
        if len(frets) <= max_frets:
            chosen = frets
        else:
            # even spread across the available range, endpoints included
            picks = np.linspace(0, len(frets) - 1, max_frets)
            chosen = sorted({frets[int(round(index))] for index in picks})
        for fret in chosen:
            key = (string, fret)
            observations.append(
                StiffnessObservation(
                    string_idx=string, fret=fret, log_b=cells[key], r2=r2_by_cell[key]
                )
            )
    return observations


def level_offset(model: StringStiffnessModel, reference: StringStiffnessModel) -> float | None:
    shifts = [
        model.log_b0[string] - reference.log_b0[string]
        for string in sorted(model.log_b0)
        if string in reference.log_b0
    ]
    return float(statistics.median(shifts)) if shifts else None


def load_cached_fits(cache: Path) -> dict[int, tuple[float, float]] | None:
    if not cache.is_file():
        return None
    raw = json.loads(cache.read_text("utf-8"))
    return {int(k): (float(v[0]), float(v[1])) for k, v in raw.items()}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-home", type=Path, default=None)
    parser.add_argument("--events-cache", type=Path, default=None)
    parser.add_argument("--fit-cache", type=Path, default=None)
    parser.add_argument("--json", dest="json_path", type=Path, default=None)
    parser.add_argument("--ritual-clips", type=int, default=RITUAL_CLIPS_PER_PLAYER)
    args = parser.parse_args()

    data_root = Path(os.environ.get("TABVISION_DATA_ROOT", ""))
    data_home = args.data_home or (data_root / "guitarset")
    events_cache = args.events_cache or (data_root / "models" / "q6_full_dev_cache")
    fit_cache = args.fit_cache or (data_root / "models" / "n5_fit_cache")

    cfg = GuitarConfig()
    session = SessionConfig()
    shipped = reference_stiffness_model()
    priors = build_oof_priors(data_home, cfg)

    all_clips = sorted(
        path.stem
        for path in (data_home / "annotation").glob("*.jams")
        if path.stem[:2] in DEV_PLAYERS
    )
    started = time.perf_counter()

    per_player: dict[str, dict[str, Any]] = {}
    # Fixed diagnostic offsets, scored on the *same* clips as every other arm.
    # N5 measured the uniform-offset response on 300 clips and left its peak
    # unlocated ("still rising at +0.60"). The ritual's median lands at +0.78,
    # so these three put N5's curve and this run's ritual on one substrate
    # instead of comparing across two different clip sets.
    fixed_offsets = (0.40, 0.60)
    fixed_labels = tuple(f"offset{value:+.2f}" for value in fixed_offsets)
    arm_labels = ("shipped", "ritual", "ritual-level", "global-level", *fixed_labels)
    deltas: dict[str, list[float]] = {label: [] for label in arm_labels}
    versus_shipped: dict[str, list[float]] = {
        label: [] for label in arm_labels if label != "shipped"
    }
    per_player_vs_shipped: dict[str, dict[str, list[float]]] = {}
    base_tab: list[float] = []
    scored_clips = 0

    # --- pass 1: calibrate every player, so the global constant can be formed
    # from ritual takes only (never from the clips it is scored on). ---------
    models: dict[str, StringStiffnessModel | None] = {}
    level_models: dict[str, StringStiffnessModel | None] = {}
    for player in DEV_PLAYERS:
        clips = [c for c in all_clips if c[:2] == player]
        ritual_clips = clips[: args.ritual_clips]
        score_clips = clips[args.ritual_clips :]

        cells, tally = measure_ritual_cells(ritual_clips, data_home, cfg, min_r2=MIN_R2)
        observations = select_ritual(cells, tally.pop("_r2"))
        model = calibrate_from_ritual(observations)
        covered = sorted(model.log_b0) if model is not None else []
        offset = level_offset(model, shipped) if model is not None else None
        level_model = offset_model(shipped, offset) if offset is not None else None
        models[player] = model
        level_models[player] = level_model

        per_player[player] = {
            "ritual_clips": ritual_clips,
            "scored_clips": len(score_clips),
            "tally": tally,
            "observations": len(observations),
            "strings_covered": covered,
            "fret_exponent": model.fret_exponent if model is not None else None,
            "level_offset": offset,
            "log_b0": {str(k): v for k, v in model.log_b0.items()} if model is not None else None,
            "shift_by_string": (
                {
                    str(s): model.log_b0[s] - shipped.log_b0[s]
                    for s in sorted(model.log_b0)
                    if s in shipped.log_b0
                }
                if model is not None
                else None
            ),
        }
        head = (
            f"player {player}: ritual {len(observations)} obs over {len(covered)}/6 strings "
            f"(admitted {tally['admitted']}/{tally['windowed']} windowed "
            f"of {tally['notes']} notes)"
        )
        if model is None:
            print(head + " -- NO MODEL", flush=True)
        else:
            shifts = per_player[player]["shift_by_string"]
            print(head + f"; exponent {model.fret_exponent:.3f}", flush=True)
            print(
                f"           level offset {offset:+.3f} log-B vs shipped; "
                f"per-string {[round(shifts[str(s)], 2) for s in covered]}",
                flush=True,
            )

    # The global constant is the median of the per-player ritual offsets. Each
    # of those came from that player's own *held-out* calibration take, so no
    # scored clip contributed to it.
    ritual_offsets = [
        info["level_offset"] for info in per_player.values() if info["level_offset"] is not None
    ]
    global_offset = float(statistics.median(ritual_offsets)) if ritual_offsets else None
    global_model = offset_model(shipped, global_offset) if global_offset is not None else None
    print(
        f"\nglobal constant = median of per-player ritual offsets = {global_offset:+.3f} log-B\n",
        flush=True,
    )

    # --- pass 2: score every player's held-out clips against all four arms --
    for player in DEV_PLAYERS:
        clips = [c for c in all_clips if c[:2] == player]
        score_clips = clips[args.ritual_clips :]
        arms = {
            "shipped": shipped,
            "ritual": models[player],
            "ritual-level": level_models[player],
            "global-level": global_model,
            **{
                label: offset_model(shipped, value)
                for label, value in zip(fixed_labels, fixed_offsets, strict=True)
            },
        }
        local: dict[str, list[float]] = {label: [] for label in versus_shipped}
        for track_id in score_clips:
            events_path = events_cache / f"{track_id}.ensemble.json"
            fits = load_cached_fits(fit_cache / f"{track_id}.fits.json")
            if not events_path.is_file() or fits is None:
                continue
            events = [_event_from_json(item) for item in json.loads(events_path.read_text("utf-8"))]
            gold = parse_guitarset_jams(data_home / "annotation" / f"{track_id}.jams", cfg)
            prior = priors[player]
            ordered = sorted(events, key=lambda event: event.onset_s)
            base_metrics, _ = _score(ordered, gold, cfg=cfg, session=session, prior=prior)
            base_tab.append(base_metrics["tab_f1"])
            scored_clips += 1
            arm_tab: dict[str, float] = {}
            for label, arm_model in arms.items():
                if arm_model is None:
                    arm_tab[label] = base_metrics["tab_f1"]
                    deltas[label].append(0.0)
                    continue
                moved, _ = apply_banked(
                    ordered, fits, arm_model, cfg, weight=WEIGHT, min_r2=MIN_R2, sigma=SIGMA
                )
                metrics, _ = _score(moved, gold, cfg=cfg, session=session, prior=prior)
                arm_tab[label] = metrics["tab_f1"]
                deltas[label].append(metrics["tab_f1"] - base_metrics["tab_f1"])
            for label in versus_shipped:
                versus_shipped[label].append(arm_tab[label] - arm_tab["shipped"])
                local[label].append(arm_tab[label] - arm_tab["shipped"])
        per_player_vs_shipped[player] = local
        summary_bits = " ".join(
            f"{label}={float(np.mean(values)):+.4f}" for label, values in local.items() if values
        )
        print(
            f"player {player}: scored {len(score_clips)} clips vs shipped -> {summary_bits} "
            f"({(time.perf_counter() - started) / 60.0:.1f} min)",
            flush=True,
        )

    rows = []
    for label, values in deltas.items():
        array = np.asarray(values, dtype=np.float64)
        ci = bootstrap_ci(array, n_bootstrap=BOOTSTRAP_N, seed=BOOTSTRAP_SEED)
        rows.append(
            {
                "label": label,
                "vs": "baseline",
                "delta": float(array.mean()),
                "lo95": ci.lower,
                "hi95": ci.upper,
            }
        )
    for label, values in versus_shipped.items():
        array = np.asarray(values, dtype=np.float64)
        ci = bootstrap_ci(array, n_bootstrap=BOOTSTRAP_N, seed=BOOTSTRAP_SEED)
        rows.append(
            {
                "label": label,
                "vs": "shipped",
                "delta": float(array.mean()),
                "lo95": ci.lower,
                "hi95": ci.upper,
            }
        )

    exponents = [
        info["fret_exponent"] for info in per_player.values() if info["fret_exponent"] is not None
    ]
    offsets = [
        info["level_offset"] for info in per_player.values() if info["level_offset"] is not None
    ]
    summary = {
        "frozen_config": {"weight": WEIGHT, "min_r2": MIN_R2, "sigma": SIGMA},
        "ritual_clips_per_player": args.ritual_clips,
        "max_frets_per_string": MAX_FRETS_PER_STRING,
        "scored_clips": scored_clips,
        "baseline_tab_f1": float(np.mean(base_tab)) if base_tab else None,
        "fret_exponent_median": float(statistics.median(exponents)) if exponents else None,
        "level_offset_median": float(statistics.median(offsets)) if offsets else None,
        "global_offset": global_offset,
        "per_player": per_player,
        "per_player_vs_shipped": {
            player: {
                label: {"n": len(values), "mean": float(np.mean(values))}
                for label, values in local.items()
                if values
            }
            for player, local in per_player_vs_shipped.items()
        },
        "arms": rows,
    }
    if args.json_path is not None:
        args.json_path.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    print(f"\nscored {scored_clips} clips, baseline Tab F1 {summary['baseline_tab_f1']:.4f}")
    print(
        f"fret exponent per player: {[round(e, 3) for e in exponents]} "
        f"(median {summary['fret_exponent_median']:.3f}, theory 1.000)"
    )
    print(
        f"level offset per player:  {[round(o, 3) for o in offsets]} "
        f"(median {summary['level_offset_median']:+.3f}, Q6 residual +0.566)"
    )
    print(f"\n{'arm':<16}{'vs':<10}{'delta':>9}{'lo95':>9}{'hi95':>9}")
    for row in rows:
        print(
            f"{row['label']:<16}{row['vs']:<10}{row['delta']:+9.4f}"
            f"{row['lo95']:+9.4f}{row['hi95']:+9.4f}"
        )
    print("\nper-player mean Tab F1 delta vs the shipped table:")
    print(
        f"{'player':<9}{'offset':>8}{'exponent':>10}{'ritual':>10}{'ritual-lvl':>12}{'global':>10}"
    )

    def cell(local: dict[str, list[float]], label: str) -> str:
        values = local.get(label) or []
        return f"{float(np.mean(values)):+.4f}" if values else "--"

    for player in DEV_PLAYERS:
        info = per_player[player]
        local = per_player_vs_shipped.get(player, {})
        offset_txt = f"{info['level_offset']:+.3f}" if info["level_offset"] is not None else "--"
        exp_txt = f"{info['fret_exponent']:.3f}" if info["fret_exponent"] is not None else "--"
        print(
            f"{player:<9}{offset_txt:>8}{exp_txt:>10}{cell(local, 'ritual'):>10}"
            f"{cell(local, 'ritual-level'):>12}{cell(local, 'global-level'):>10}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
